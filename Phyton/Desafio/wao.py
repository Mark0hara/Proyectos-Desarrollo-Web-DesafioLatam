
# LISTA: El índice es la POSICIÓN (empieza en 0)
lista = [25, 31, "hola"]
print(lista[0])  # Imprime 25 (posición 0)
print(lista[2])  # Imprime "hola" (posición 2)

# DICCIONARIO: El índice es la CLAVE (la inventas tú)
diccionario = {"a": 25, "b": 31, "c": "hola"}
print(diccionario["b"])  # Imprime 31 (porque la clave "b" vale 31)
print(diccionario["c"])  # Imprime "hola" (porque la clave "c" vale "hola")